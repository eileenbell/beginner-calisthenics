import type { Exercise } from "../types";

// The exercise catalogue. This file is the single source of truth for
// exercise metadata: the database reference data migration is generated from it
// by scripts/generate-reference-data.ts, and a test fails if the two drift apart.
//
// Every entry is written for someone with no fitness background. Source codes
// (S1, S6 ...) refer to docs/research/SOURCES.md. Validation status is
// "internal_review" for every exercise: none has been reviewed by a qualified
// professional yet (see docs/EXERCISE_CONTENT_REVIEW.md).

type ExerciseInput = Omit<
  Exercise,
  "secondaryMuscles" | "alternatives" | "perSide" | "isLadderStep" | "validation" | "goals"
> &
  Partial<Pick<Exercise, "secondaryMuscles" | "alternatives" | "perSide" | "isLadderStep" | "goals">> & {
    sources?: string[];
    reviewNotes?: string;
  };

function ex(input: ExerciseInput): Exercise {
  const { sources, reviewNotes, ...rest } = input;
  return {
    secondaryMuscles: [],
    alternatives: [],
    perSide: false,
    isLadderStep: true,
    goals: [],
    ...rest,
    validation: {
      status: "internal_review",
      sources: sources ?? ["S12"],
      reviewNotes,
    },
  };
}


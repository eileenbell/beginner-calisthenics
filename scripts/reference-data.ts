// Builds the SQL that loads FORM's reference data (exercises, progression
// relationships, skills, milestones and achievements) into Postgres.
//
// The TypeScript catalogue in src/domain/content is the single source of
// truth. `npm run db:reference` writes the output to a migration file, and
// tests/unit/reference-data.test.ts fails if that file drifts from the
// catalogue, so the database can never silently disagree with the app.

import { EXERCISES } from "../src/domain/content/exercises";
import { ACHIEVEMENTS, SKILLS } from "../src/domain/content/skills";
import { easierLibraryOptions, harderOptions } from "../src/domain/engine/catalogue";

export const REFERENCE_MIGRATION = "supabase/migrations/20261024000300_reference_data.sql";

function lit(value: string | null | undefined): string {
  if (value === null || value === undefined) return "null";
  return `'${value.replace(/'/g, "''")}'`;
}

function arr(values: readonly string[]): string {
  return values.length === 0 ? "'{}'::text[]" : `array[${values.map(lit).join(", ")}]::text[]`;
}

function json(value: unknown): string {
  return `${lit(JSON.stringify(value))}::jsonb`;
}

export function buildReferenceSql(): string {
  const out: string[] = [];
  out.push("-- GENERATED by scripts/reference-data.ts from src/domain/content. Do not edit by hand.");
  out.push("-- Regenerate with `npm run db:reference` and commit the result as a new migration when content changes.");
  out.push("");

  for (const e of EXERCISES) {
    const content = {
      surfaces: e.surfaces ?? null,
      goals: e.goals,
      dosage: e.dosage,
      why: e.why,
      setup: e.setup,
      steps: e.steps,
      breathing: e.breathing,
      goodControl: e.goodControl,
      cues: e.cues,
      mistakes: e.mistakes,
      safety: e.safety,
      alternatives: e.alternatives,
      extraEasier: e.extraEasier ?? [],
      limitationNote: e.limitationNote ?? null,
      sources: e.validation.sources,
      reviewNotes: e.validation.reviewNotes ?? null,
    };
    out.push(
      `insert into public.exercises (id, name, family_id, level, difficulty, pattern, category, measure, per_side, is_ladder_step, primary_muscles, secondary_muscles, equipment_any_of, equipment_all_of, content, validation_status) values (` +
        [
          lit(e.id),
          lit(e.name),
          lit(e.familyId),
          e.level,
          e.difficulty,
          lit(e.pattern),
          lit(e.category),
          lit(e.measure),
          e.perSide,
          e.isLadderStep,
          arr(e.primaryMuscles),
          arr(e.secondaryMuscles),
          arr(e.equipmentAnyOf),
          arr(e.equipmentAllOf ?? []),
          json(content),
          lit(e.validation.status),
        ].join(", ") +
        `) on conflict (id) do update set name = excluded.name, family_id = excluded.family_id, level = excluded.level, difficulty = excluded.difficulty, pattern = excluded.pattern, category = excluded.category, measure = excluded.measure, per_side = excluded.per_side, is_ladder_step = excluded.is_ladder_step, primary_muscles = excluded.primary_muscles, secondary_muscles = excluded.secondary_muscles, equipment_any_of = excluded.equipment_any_of, equipment_all_of = excluded.equipment_all_of, content = excluded.content, validation_status = excluded.validation_status;`,
    );
  }

  out.push("");
  out.push("delete from public.exercise_progressions;");
  const relations = new Set<string>();
  for (const e of EXERCISES) {
    for (const h of harderOptions(e.id)) relations.add(`${e.id}|${h.id}|harder`);
    for (const h of easierLibraryOptions(e.id)) relations.add(`${e.id}|${h.id}|easier`);
    for (const a of e.alternatives) relations.add(`${e.id}|${a}|alternative`);
  }
  for (const r of [...relations].sort()) {
    const [from, to, relation] = r.split("|");
    out.push(`insert into public.exercise_progressions (from_exercise_id, to_exercise_id, relation) values (${lit(from)}, ${lit(to)}, ${lit(relation)});`);
  }

  out.push("");
  SKILLS.forEach((s, index) => {
    out.push(
      `insert into public.skills (id, name, summary, families, equipment_any_of, gate, sort_order) values (${lit(s.id)}, ${lit(s.name)}, ${lit(s.summary)}, ${arr(s.families)}, ${arr(s.equipmentAnyOf)}, ${s.gate ? json(s.gate) : "null"}, ${index + 1}) on conflict (id) do update set name = excluded.name, summary = excluded.summary, families = excluded.families, equipment_any_of = excluded.equipment_any_of, gate = excluded.gate, sort_order = excluded.sort_order;`,
    );
    for (const m of s.milestones) {
      out.push(
        `insert into public.skill_milestones (id, skill_id, sort_order, title, description, exercise_id, sets, min_reps, min_seconds) values (${lit(m.id)}, ${lit(s.id)}, ${m.order}, ${lit(m.title)}, ${lit(m.description)}, ${lit(m.exerciseId)}, ${m.sets}, ${m.minReps ?? "null"}, ${m.minSeconds ?? "null"}) on conflict (id) do update set skill_id = excluded.skill_id, sort_order = excluded.sort_order, title = excluded.title, description = excluded.description, exercise_id = excluded.exercise_id, sets = excluded.sets, min_reps = excluded.min_reps, min_seconds = excluded.min_seconds;`,
      );
    }
  });

  out.push("");
  for (const a of ACHIEVEMENTS) {
    out.push(
      `insert into public.achievements (id, title, description) values (${lit(a.id)}, ${lit(a.title)}, ${lit(a.description)}) on conflict (id) do update set title = excluded.title, description = excluded.description;`,
    );
  }
  out.push("");
  return out.join("\n");
}
